import re


# 移除非 hex 的內容與換行
cleaned = re.sub(r'[^\dA-Fa-f]', ' ', hex_data)
data = [int(b, 16) for b in cleaned.strip().split() if b]

def get_sprites_data():
    return convert_interleaved_to_sprites(data)

def convert_interleaved_to_sprites(data, num_sprites=104, sprite_size=22):
    sprites = []
    for sprite_index in range(num_sprites):
        sprite = []
        for byte_index in range(sprite_size):
            i = sprite_index + byte_index * num_sprites
            sprite.append(data[i])
        sprites.append(sprite)
    return sprites

def format_js_array(sprites):
    lines = ["const sprites_data = ["]
    for idx, sprite in enumerate(sprites):
        hex_bytes = ', '.join(f'0x{b:02X}' for b in sprite)
        lines.append(f"  // Sprite {idx}")
        lines.append(f"  new Uint8Array([{hex_bytes}]),")
    lines.append("];")
    return '\n'.join(lines)

def main():
    import sys

    if len(data) != 104 * 22:
        raise ValueError(f"Expected 2296 bytes (104 sprites × 22 bytes), got {len(data)}")

    sprites = convert_interleaved_to_sprites(data)
    js_code = format_js_array(sprites)

    with open('dat_sprites.js', 'w') as f:
        f.write(js_code)

if __name__ == "__main__":
    main()

